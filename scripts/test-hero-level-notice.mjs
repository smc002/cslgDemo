import assert from 'node:assert/strict';
import { build } from 'esbuild';
await build({entryPoints:['lib/campaign.ts'],bundle:true,platform:'node',format:'esm',outfile:'.test-cache/hero-level-notice.mjs'});
const storage = new Map(), handlers = new Map();
globalThis.localStorage = {getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
globalThis.window = {location:{search:''},addEventListener:(name,fn)=>handlers.set(name,fn)};
const {campaign, freshCampaign, saveHunt, KEY} = await import('../.test-cache/hero-level-notice.mjs');
const saved = freshCampaign();
saved.hunt.level = 2; saved.hunt.expedition.points = 200;
localStorage.setItem(KEY,JSON.stringify(saved));
const events=[];
const unsubscribe=campaign.subscribeHeroLevelUps((level,heroes)=>events.push({level,heroes}));
campaign.init(); campaign.claim();
assert.equal(events.length,0,'loading existing levels never replays a notice');
const levelUp = () => campaign.update(d=>{
  const h=structuredClone(d.hunt);
  h.expedition.points+=h.level*200-h.xp; h.xp=0; h.level++;
  assert.equal(saveHunt(d,h),true);
});
campaign.update(d=>{d.hunt.expedition.points+=20;d.hunt.xp+=20;});
assert.equal(events.length,0,'partial core progress is not a level-up');
levelUp();
assert.deepEqual(events,[{level:3,heroes:[0,1,2]}],'each owned hero, including the healer, gets a notice');
campaign.update(d=>{assert.equal(saveHunt(d,structuredClone(d.hunt)),true);});
assert.equal(events.length,1,'repeated hunt saves never repeat notices');
campaign.update(d=>{Object.keys(d.recruit.owned).forEach(k=>d.recruit.owned[k]=1);d.lineup=Array(9).fill(-1);});
levelUp(); levelUp();
assert.deepEqual(events.slice(1),[{level:4,heroes:[0,1,2,3,4,5,6,7,8]},{level:5,heroes:[0,1,2,3,4,5,6,7,8]}],'all nine heroes, even on the bench, are delivered for consecutive upgrades');
const remote=structuredClone(campaign.read());remote.hunt.level++;remote.hunt.expedition.points+=1000;
handlers.get('storage')({key:KEY,newValue:JSON.stringify(remote)});
campaign.update(()=>{});
assert.equal(events.length,3,'remote saves do not replay notices');
campaign.reset();
assert.equal(events.length,3,'reset does not announce upgrades');
localStorage.setItem('mori.demo.lease.v2',JSON.stringify({owner:'other',until:Date.now()+10000}));
assert.equal(levelUp(),false);
assert.equal(events.length,3,'rejected updates have no notice');
campaign.claim(true); unsubscribe(); levelUp();
assert.equal(events.length,3,'unmounted subscriptions are removed');
console.log('PASS hero level notices: actual core upgrades, every owned hero, bench heroes, consecutive upgrades, no load/save/sync/reset duplicates, ownership and cleanup');
